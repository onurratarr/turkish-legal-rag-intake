"""Automatic rubric for RAG answers + eval runner over the synthetic Q&A set.

Metrics (each 0-1):
* grounding           - share of answer sentences whose content is supported by the chunk they cite
* citation_precision  - cited sources that are expected / all cited sources
* citation_recall     - expected sources that are cited / all expected sources
* completeness        - required facts (must_include) present in the answer
* abstention_correct  - abstained iff the question is unanswerable from the corpus
A question passes if it abstains correctly, or (when answerable) grounding >= 0.8, citation_precision >= 0.5,
citation_recall >= 0.5 and completeness >= 0.67.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from statistics import mean

from .answer import CITATION_RE, DISCLAIMER, Answer, LegalAssistant
from .corpus import Chunk, load_corpus
from .retrieval import BM25Retriever
from .text import content_stems, normalize, sentences

QA_FILE = Path(__file__).resolve().parent.parent / "data" / "eval" / "qa.jsonl"
BOILERPLATE = ("Kaynaklara göre:", DISCLAIMER)


def grounding_score(answer_text: str, chunks_by_id: dict[str, Chunk], threshold: float = 0.6) -> float:
    text = answer_text
    for b in BOILERPLATE:
        text = text.replace(b, " ")
    parts = CITATION_RE.split(text)  # [seg, cite, seg, cite, ..., tail]
    judged: list[bool] = []
    for i in range(0, len(parts), 2):
        seg = re.sub(r"^\s*-\s*", "", parts[i]).strip()
        cite = parts[i + 1] if i + 1 < len(parts) else None
        support = set(content_stems(chunks_by_id[cite].text)) if cite in chunks_by_id else set()
        for s in sentences(seg.replace("\n- ", " ")):
            stems = content_stems(s)
            if not stems:
                continue
            judged.append(bool(support) and sum(t in support for t in stems) / len(stems) >= threshold)
    return round(sum(judged) / len(judged), 3) if judged else 0.0


def score(answer: Answer, item: dict, chunks_by_id: dict[str, Chunk]) -> dict:
    expected = set(item["expected_citations"])
    if not item["answerable"]:
        ok = answer.abstained
        return {"id": item["id"], "answerable": False, "abstention_correct": float(ok), "grounding": None,
                "citation_precision": None, "citation_recall": None, "completeness": None, "passed": ok}
    if answer.abstained:
        return {"id": item["id"], "answerable": True, "abstention_correct": 0.0, "grounding": 0.0,
                "citation_precision": 0.0, "citation_recall": 0.0, "completeness": 0.0, "passed": False}
    cited = set(answer.citations)
    norm = normalize(answer.text)
    res = {
        "id": item["id"], "answerable": True, "abstention_correct": 1.0,
        "grounding": grounding_score(answer.text, chunks_by_id),
        "citation_precision": round(len(cited & expected) / len(cited), 3) if cited else 0.0,
        "citation_recall": round(len(cited & expected) / len(expected), 3) if expected else 1.0,
        "completeness": round(float(mean(normalize(f) in norm for f in item["must_include"])), 3) if item["must_include"] else 1.0,
    }
    res["passed"] = (res["grounding"] >= 0.8 and res["citation_precision"] >= 0.5
                     and res["citation_recall"] >= 0.5 and res["completeness"] >= 0.67)
    return res


def run_eval(assistant: LegalAssistant | None = None, qa_file: str | Path = QA_FILE) -> dict:
    chunks = load_corpus()
    assistant = assistant or LegalAssistant(BM25Retriever(chunks))
    by_id = {c.cite_id: c for c in chunks}
    items = [json.loads(line) for line in Path(qa_file).read_text(encoding="utf-8").splitlines() if line.strip()]
    rows = [score(assistant.ask(it["question"]), it, by_id) for it in items]
    ans = [r for r in rows if r["answerable"]]

    def avg(key: str) -> float:
        return round(mean(r[key] for r in ans), 3) if ans else 0.0

    summary = {"n": len(rows), "pass_rate": round(float(mean(r["passed"] for r in rows)), 3),
               "abstention_accuracy": round(mean(r["abstention_correct"] for r in rows), 3),
               **{k: avg(k) for k in ("grounding", "citation_precision", "citation_recall", "completeness")}}
    return {"backend": getattr(assistant.answerer, "name", "custom"), "summary": summary, "rows": rows}


def to_markdown(result: dict) -> str:
    s = result["summary"]
    fmt = lambda v: "–" if v is None else (f"{v:.2f}" if isinstance(v, float) else str(v))  # noqa: E731
    out = [f"# Eval results — synthetic data, `{result['backend']}` backend", "",
           "Generated by `python -m legal_rag.evaluate`. Synthetic corpus and synthetic Q&A set; these numbers describe",
           "this demo only and say nothing about any real deployment.", "",
           "| metric | value |", "|---|---|", *[f"| {k} | {fmt(v)} |" for k, v in s.items()], "",
           "| id | answerable | grounding | cit. precision | cit. recall | completeness | abstention ok | pass |",
           "|---|---|---|---|---|---|---|---|"]
    for r in result["rows"]:
        out.append(f"| {r['id']} | {r['answerable']} | {fmt(r['grounding'])} | {fmt(r['citation_precision'])} | "
                   f"{fmt(r['citation_recall'])} | {fmt(r['completeness'])} | {fmt(r['abstention_correct'])} | "
                   f"{'✅' if r['passed'] else '❌'} |")
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description="Run the rubric eval on the synthetic Q&A set.")
    ap.add_argument("--out", default="eval/results.md")
    ap.add_argument("--json", default=None)
    args = ap.parse_args()
    result = run_eval()
    md = to_markdown(result)
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text(md, encoding="utf-8")
    if args.json:
        Path(args.json).write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
